#!/usr/bin/env bash
# Regenerate data/contributors.yaml, the contributors shown in the home page's
# open source section. Needs the GitHub CLI (gh), logged in.
set -eu

REPOS="plakar kloset integrations"
# Accounts that are not people, such as AI coding agents
SKIP="claude"
OUT="$(dirname "$0")/../data/contributors.yaml"

{
  echo "# Generated by scripts/update-contributors.sh, do not edit by hand."
  echo "# Humans who contributed to PlakarKorp/{${REPOS// /,}}, most contributions first."
  for repo in $REPOS; do
    gh api "repos/PlakarKorp/$repo/contributors?per_page=100" --paginate \
      --jq '.[] | select(.type == "User") | [.login, .id, .contributions] | @tsv'
  done | grep -v -i -w -F -f <(printf '%s\n' $SKIP) | awk -F'\t' '{ n[$1] += $3; id[$1] = $2 } END { for (l in n) print n[l] "\t" l "\t" id[l] }' \
    | sort -rn \
    | awk -F'\t' '{ printf "- login: %s\n  id: %s\n", $2, $3 }'
} > "$OUT"

echo "wrote $(grep -c '^- login' "$OUT") contributors to $OUT"
